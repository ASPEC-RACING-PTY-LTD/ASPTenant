import type { ConfigShape } from './define.js';
import { collectMeta } from './define.js';
import { EnvField, type FieldMeta } from './fields.js';

function placeholder(meta: FieldMeta): string {
  if (meta.secret) return '';
  if (meta.example !== undefined) return meta.example;
  if (meta.hasDefault && meta.defaultValue !== undefined) {
    if (Array.isArray(meta.defaultValue)) return meta.defaultValue.join(',');
    if (typeof meta.defaultValue === 'boolean') return meta.defaultValue ? 'true' : 'false';
    return String(meta.defaultValue);
  }
  switch (meta.kind) {
    case 'port':
      return '3000';
    case 'boolean':
      return 'true';
    case 'url':
      return 'https://example.com';
    case 'email':
      return 'user@example.com';
    case 'duration':
      return '30s';
    case 'bytes':
      return '10MB';
    default:
      return '';
  }
}

/** Generates a `.env.example` file. Secret values are empty placeholders only. */
export function generateEnvExample(shape: ConfigShape): string {
  const lines: string[] = ['# Generated by @aspec/config. Secrets are left blank on purpose.'];
  for (const meta of collectMeta(shape)) {
    if (meta.description) lines.push(`# ${meta.description}`);
    if (meta.secret) lines.push(`# secret`);
    lines.push(`${meta.name}=${placeholder(meta)}`);
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

/** Markdown documentation. Secret defaults are never shown. */
export function generateMarkdownDocs(shape: ConfigShape, title = 'Environment variables'): string {
  const lines = [
    `# ${title}`,
    '',
    '| Variable | Type | Required | Default | Description |',
    '|----------|------|----------|---------|-------------|',
  ];
  for (const meta of collectMeta(shape)) {
    const required = meta.hasDefault ? 'no' : 'yes';
    const def =
      meta.secret || !meta.hasDefault
        ? meta.secret
          ? '*(secret)*'
          : 'none'
        : `\`${formatDefault(meta.defaultValue)}\``;
    const desc = (meta.description ?? '').replace(/\|/g, '\\|');
    lines.push(`| \`${meta.name}\` | ${meta.kind} | ${required} | ${def} | ${desc} |`);
  }
  return `${lines.join('\n')}\n`;
}

function formatDefault(value: unknown): string {
  if (Array.isArray(value)) return value.join(',');
  if (typeof value === 'string') return value;
  return JSON.stringify(value);
}

/** JSON Schema (2020-12) for the environment object keyed by variable name. */
export function toJSONSchema(shape: ConfigShape): Record<string, unknown> {
  const properties: Record<string, unknown> = {};
  const required: string[] = [];
  for (const meta of collectMeta(shape)) {
    properties[meta.name] = fieldSchema(meta);
    if (!meta.hasDefault) required.push(meta.name);
  }
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    type: 'object',
    additionalProperties: false,
    properties,
    ...(required.length ? { required } : {}),
  };
}

function fieldSchema(meta: FieldMeta): Record<string, unknown> {
  const base: Record<string, unknown> = { title: meta.name };
  if (meta.description) base.description = meta.description;
  if (meta.secret) base.writeOnly = true;
  switch (meta.kind) {
    case 'number':
    case 'duration':
    case 'bytes':
      return {
        ...base,
        type: 'string',
        description: `${meta.description ?? meta.kind} (parsed from string)`,
      };
    case 'integer':
    case 'port':
      return { ...base, type: 'string', pattern: '^[0-9]+$' };
    case 'boolean':
      return {
        ...base,
        type: 'string',
        enum: ['true', 'false', '1', '0', 'yes', 'no', 'on', 'off'],
      };
    case 'list':
      return { ...base, type: 'string' };
    default:
      return { ...base, type: 'string' };
  }
}

/** Walk a shape and return EnvField instances (for CLI introspection). */
export function listFields(shape: ConfigShape): EnvField<unknown>[] {
  const out: EnvField<unknown>[] = [];
  const walk = (s: ConfigShape) => {
    for (const field of Object.values(s)) {
      if (field instanceof EnvField) out.push(field);
      else walk(field);
    }
  };
  walk(shape);
  return out;
}
